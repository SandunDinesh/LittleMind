"""
generate_synthetic_v2.py  -  LittleMind synthetic development dataset, version 2

Creates 10,000 SYNTHETIC, NON-CLINICAL drawing-feature records for children aged 3-6.

What is new compared with child_art_stress_synthetic_dataset.csv (V1, 250 rows):
  1. Feature values are calibrated to what src/art_feature_extractor.py actually
     outputs on real scanned children's drawings (V1 used invented scales, e.g.
     texture_entropy ~4.9 vs ~0.5 on real images; stroke thickness ~2.8px vs ~32px).
  2. Feature correlations come from a Gaussian copula fitted to real extractor output.
  3. Deterministic relations of the extractor are kept
     (whitespace = 1 - drawing_area, object_count = shape_count,
      pressure_proxy_darkness = 1 - mean_value_brightness).
  4. Age group is "3-6" (matches the API), with age-year developmental shifts.
  5. Children have 1-4 drawings; the train/validation/test split is done BY CHILD.
  6. Labels are deliberately noisy (simulated rater disagreement) so that the
     benchmark cannot be reconstructed perfectly from a few features.
  7. Depicted-content flag columns (content_*) are added. Real images need a
     separate content detector or a human reviewer to fill them; the OpenCV
     extractor does NOT produce them.

THE LABELS ARE GENERATED BY THE RULES IN THIS FILE. A model trained on this data
learns these rules, not real child stress. Never report results from this data as
stress- or abuse-detection accuracy.

Usage:
    python generate_synthetic_v2.py --calibration kido_pilot_features.csv --n 10000 --seed 2026
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

FEATURE_COLS = [
    "mean_hue_deg", "mean_saturation", "mean_value_brightness", "warm_color_ratio",
    "cool_color_ratio", "dark_color_ratio", "bright_color_ratio", "red_ratio", "blue_ratio",
    "green_ratio", "yellow_ratio", "black_gray_ratio", "dominant_color_count",
    "color_variety_score", "edge_density", "line_count", "avg_line_length_px",
    "line_length_std_px", "stroke_thickness_avg_px", "stroke_thickness_std_px",
    "broken_line_ratio", "horizontal_line_ratio", "vertical_line_ratio",
    "diagonal_line_ratio", "curved_line_ratio", "orientation_entropy",
    "closed_contour_ratio", "shape_count", "drawing_area_ratio",
    "center_occupancy_ratio", "left_right_symmetry_score", "top_bottom_balance_score",
    "texture_entropy", "contrast_score", "scribble_density", "scan_quality_score",
]
INTEGER_COLS = {"dominant_color_count", "line_count", "shape_count"}
RATIO_COLS = {c for c in FEATURE_COLS if c.endswith(("_ratio", "_score", "_density", "_entropy"))
              or c in {"mean_saturation", "mean_value_brightness", "color_variety_score"}}

# Output column order: identical to V1 so src/train_model.py works unchanged,
# plus the new content_* columns before the label columns.
V1_ORDER = [
    "child_art_id", "image_id", "age_group", "drawing_prompt", "scan_quality_score", "data_split",
    "mean_hue_deg", "mean_saturation", "mean_value_brightness", "warm_color_ratio",
    "cool_color_ratio", "dark_color_ratio", "bright_color_ratio", "red_ratio", "blue_ratio",
    "green_ratio", "yellow_ratio", "black_gray_ratio", "dominant_color_count",
    "color_variety_score", "edge_density", "line_count", "avg_line_length_px",
    "line_length_std_px", "stroke_thickness_avg_px", "stroke_thickness_std_px",
    "broken_line_ratio", "horizontal_line_ratio", "vertical_line_ratio",
    "diagonal_line_ratio", "curved_line_ratio", "orientation_entropy",
    "closed_contour_ratio", "shape_count", "object_count", "drawing_area_ratio",
    "whitespace_ratio", "center_occupancy_ratio", "left_right_symmetry_score",
    "top_bottom_balance_score", "texture_entropy", "contrast_score", "scribble_density",
    "erasure_marks_ratio", "pressure_proxy_darkness",
]
CONTENT_COLS = [
    "content_aggression_depicted",   # one figure hitting / hurting another
    "content_crying_figure",         # tears / crying face
    "content_isolated_figure",       # single small figure apart from others
    "content_weapon_depicted",
    "content_injury_depicted",
    "content_adult_child_conflict",  # larger figure confronting smaller figure
]
LABEL_COLS = ["label_source", "stress_score_0_100", "stress_level"]

# Hypothesised (NOT validated) direction of association with the synthetic latent,
# expressed in standard-normal (copula) units per 1 SD of latent.
STRESS_EFFECTS = {
    "dark_color_ratio": 0.45, "black_gray_ratio": 0.45,
    "scribble_density": 0.40, "edge_density": 0.20, "broken_line_ratio": 0.25,
    "color_variety_score": -0.35, "mean_saturation": -0.25, "warm_color_ratio": -0.20,
    "bright_color_ratio": -0.30, "mean_value_brightness": -0.30,
    "drawing_area_ratio": -0.25, "left_right_symmetry_score": -0.20,
    "center_occupancy_ratio": -0.15, "dominant_color_count": -0.20,
}
# Developmental shift per year above age 3 (3-year-olds scribble more, draw fewer
# closed shapes and straight lines). Hypothesised, for realism of the benchmark only.
AGE_EFFECTS = {
    "scribble_density": -0.25, "closed_contour_ratio": 0.20, "line_count": 0.15,
    "shape_count": 0.15, "left_right_symmetry_score": 0.10, "orientation_entropy": 0.10,
    "curved_line_ratio": -0.10,
}
CONTENT_BASE = {  # logit intercept, slope on latent
    "content_aggression_depicted": (-4.6, 1.3),
    "content_crying_figure": (-3.6, 1.1),
    "content_isolated_figure": (-2.6, 0.8),
    "content_weapon_depicted": (-5.6, 1.2),
    "content_injury_depicted": (-5.4, 1.2),
    "content_adult_child_conflict": (-4.4, 1.3),
}
PROMPTS = ["Free drawing", "Draw your family", "Draw yourself", "Draw your home"]


def fit_copula(calib: pd.DataFrame):
    X = calib[FEATURE_COLS].astype(float)
    U = X.rank(method="average").values / (len(X) + 1)
    Z = stats.norm.ppf(U)
    C = np.corrcoef(Z, rowvar=False)
    C = np.nan_to_num(C)
    np.fill_diagonal(C, 1.0)
    C = 0.6 * C + 0.4 * np.eye(len(FEATURE_COLS))  # shrinkage: only 50 calibration rows
    # make positive definite
    w, v = np.linalg.eigh(C)
    C = v @ np.diag(np.clip(w, 1e-3, None)) @ v.T
    d = np.sqrt(np.diag(C)); C = C / np.outer(d, d)
    return C


def inverse_marginal(col: str, z: np.ndarray, calib: pd.DataFrame, rng) -> np.ndarray:
    vals = np.sort(calib[col].astype(float).values)
    lo, hi = vals.min(), vals.max()
    span = (hi - lo) if hi > lo else max(abs(hi), 1.0)
    # smoothed empirical quantile function with modest tail extension
    q = np.linspace(0, 1, len(vals))
    u = stats.norm.cdf(z)
    out = np.interp(u, q, vals)
    out = out + rng.normal(0, 0.04 * span, size=len(z))
    lo2, hi2 = lo - 0.10 * span, hi + 0.10 * span
    if col in RATIO_COLS:
        lo2, hi2 = max(lo2, 0.0), min(hi2, 1.0)
    else:
        lo2 = max(lo2, 0.0)
    if col == "mean_hue_deg":
        lo2, hi2 = 0.0, 359.9
    return np.clip(out, lo2, hi2)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--calibration", required=True, help="CSV of real extractor outputs")
    ap.add_argument("--n", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", default="child_art_stress_synthetic_v2_10k.csv")
    ap.add_argument("--meta-out", default="child_art_stress_synthetic_v2_10k_metadata.csv")
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    calib = pd.read_csv(args.calibration)
    C = fit_copula(calib)
    k = len(FEATURE_COLS)

    # ---- children and drawings -------------------------------------------------
    child_rows, n = [], 0
    cid = 0
    while n < args.n:
        cid += 1
        m = int(min(rng.choice([1, 2, 3, 4], p=[0.30, 0.35, 0.25, 0.10]), args.n - n))
        child_rows.append((f"CH_{cid:05d}", m, int(rng.integers(3, 7)),
                           float(rng.normal())))  # child-level latent
        n += m
    recs = []
    for child_id, m, age, child_latent in child_rows:
        for j in range(m):
            recs.append({"child_id": child_id, "drawing_index": j + 1, "age_years": age,
                         "child_latent": child_latent})
    meta = pd.DataFrame(recs)
    N = len(meta)
    # drawing-level latent = stable child component + occasion-specific component
    latent = 0.75 * meta["child_latent"].values + 0.66 * rng.normal(size=N)
    latent = (latent - latent.mean()) / latent.std()

    # ---- features via copula + effects ------------------------------------------
    Z = rng.multivariate_normal(np.zeros(k), C, size=N)
    age_c = meta["age_years"].values - 4.5
    for i, col in enumerate(FEATURE_COLS):
        Z[:, i] += STRESS_EFFECTS.get(col, 0.0) * latent + AGE_EFFECTS.get(col, 0.0) * age_c
    df = pd.DataFrame({col: inverse_marginal(col, Z[:, i], calib, rng)
                       for i, col in enumerate(FEATURE_COLS)})
    for col in INTEGER_COLS:
        df[col] = np.maximum(1, np.round(df[col])).astype(int)

    # deterministic extractor relations
    df["whitespace_ratio"] = 1.0 - df["drawing_area_ratio"]
    df["object_count"] = df["shape_count"]
    df["pressure_proxy_darkness"] = 1.0 - df["mean_value_brightness"]
    # line orientation ratios must sum to 1
    s = df[["horizontal_line_ratio", "vertical_line_ratio", "diagonal_line_ratio"]].sum(axis=1).replace(0, 1)
    for c in ["horizontal_line_ratio", "vertical_line_ratio", "diagonal_line_ratio"]:
        df[c] = df[c] / s
    # erasure proxy: almost always ~0 on real scans; rare small values
    df["erasure_marks_ratio"] = np.where(rng.random(N) < 0.08 + 0.04 * (latent > 1),
                                         rng.gamma(1.5, 0.004, N), 0.0)
    df["bright_color_ratio"] = np.minimum(df["bright_color_ratio"], 1 - df["dark_color_ratio"])

    # ---- depicted-content flags -------------------------------------------------
    for col, (b0, b1) in CONTENT_BASE.items():
        p = 1 / (1 + np.exp(-(b0 + b1 * latent)))
        df[col] = (rng.random(N) < p).astype(int)
    # adult-child conflict and aggression co-occur
    both = (df["content_adult_child_conflict"] == 1) & (rng.random(N) < 0.6)
    df.loc[both, "content_aggression_depicted"] = 1
    severe = df[["content_aggression_depicted", "content_weapon_depicted",
                 "content_injury_depicted", "content_adult_child_conflict"]].max(axis=1)

    # ---- labels (synthetic rules + noise) -------------------------------------
    score = (45 + 15 * latent + 12 * severe + 5 * df["content_crying_figure"]
             + rng.normal(0, 9, N))
    score = np.clip(np.round(score), 0, 100).astype(int)
    level = np.where(score >= 65, "High", np.where(score >= 38, "Moderate", "Low"))
    # simulated rater disagreement: 10% moved to an adjacent class
    flip = rng.random(N) < 0.10
    order = np.array(["Low", "Moderate", "High"])
    idx = np.array([list(order).index(x) for x in level])
    step = np.where(rng.random(N) < 0.5, -1, 1)
    new = np.clip(idx + step, 0, 2)
    level = np.where(flip, order[new], level)

    # ---- assemble -----------------------------------------------------------
    ids = [f"SYN2_{i:05d}" for i in range(1, N + 1)]
    df.insert(0, "child_art_id", ids)
    df.insert(1, "image_id", [f"syn2_{i:05d}.png" for i in range(1, N + 1)])
    df.insert(2, "age_group", "3-6")
    df.insert(3, "drawing_prompt", rng.choice(PROMPTS, size=N, p=[0.4, 0.25, 0.2, 0.15]))
    # child-level split 70/15/15
    children = meta["child_id"].unique()
    rng.shuffle(children)
    a, b = int(0.70 * len(children)), int(0.85 * len(children))
    split_of = {c: "train" for c in children[:a]}
    split_of.update({c: "validation" for c in children[a:b]})
    split_of.update({c: "test" for c in children[b:]})
    df["data_split"] = meta["child_id"].map(split_of).values
    df["label_source"] = "synthetic_v2_not_clinical"
    df["stress_score_0_100"] = score
    df["stress_level"] = level

    for c in df.columns:
        if df[c].dtype == float:
            df[c] = df[c].round(4)
    df = df[V1_ORDER + CONTENT_COLS + LABEL_COLS]
    df.to_csv(args.out, index=False)

    meta_out = pd.DataFrame({
        "child_art_id": ids, "child_id": meta["child_id"], "drawing_index": meta["drawing_index"],
        "age_years": meta["age_years"], "data_split": df["data_split"],
        "latent_stress_z": np.round(latent, 4),
        "review_label_synthetic": ((df["stress_level"] == "High") | (severe == 1)).astype(int),
        "label_flipped_rater_noise": flip.astype(int),
    })
    meta_out.to_csv(args.meta_out, index=False)
    print(f"Saved {len(df)} rows -> {args.out}")
    print(df["stress_level"].value_counts().to_string())
    print(df["data_split"].value_counts().to_string())


if __name__ == "__main__":
    main()
